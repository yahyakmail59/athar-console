-- اختيار صريح لما يُعرض في موقع أثر، وبيانات دخول التجربة.
--
-- كان الشرط ضمنيًّا: كل مستأجر `demo` نشط له رابط عام يُدفَع إلى الموقع.
-- فظهرت ثمانيةُ مستأجرين دفعةً واحدة، فيهم أسماء تبدو أسماء زبائن حقيقيين
-- (صيدلية أسماء، عيادة السلام2) وروابط دخولهم معلنة لكل زائر. والوضع
-- التجريبي حالةُ تشغيلٍ لا قرارَ عرض، فبناء النشر عليه ينشر ما لم يُقصد.
--
-- `is_showcase` تجعله قرارًا يُتَّخذ لا أثرًا جانبيًّا. والافتراضي صفر:
-- مستأجر جديد لا يظهر حتى يُختار.
ALTER TABLE tenants ADD COLUMN is_showcase INTEGER NOT NULL DEFAULT 0;

-- بيانات دخول التجربة، تُعرض علنًا في الموقع.
--
-- الزائر كان يضغط «افتح التجربة» فيصطدم بشاشة دخول بلا اسم ولا كلمة —
-- خمسٌ من ثماني تجارب كانت كذلك — فيغادر. وبطاقةٌ تَعِد بتجربة ثم تسأل
-- كلمة مرور أسوأ من غياب البطاقة.
--
-- وكلمة المرور هنا **منشورة عمدًا**، فلا تُوضع إلا على نسخة تجريبية
-- ببيانات مبذورة يُستهان بفقدها. الحارس في التطبيق: `is_showcase` لا
-- تُقبل إلا مع `environment = 'demo'`.
ALTER TABLE tenants ADD COLUMN demo_username TEXT NOT NULL DEFAULT '';
ALTER TABLE tenants ADD COLUMN demo_password TEXT NOT NULL DEFAULT '';

-- سطر يشرح للزائر ماذا يجرّب في هذه النسخة تحديدًا. الوصف العامّ
-- «بيانات واقعية وكل الوظائف» لا يقول له ماذا يفعل بعد أن يدخل.
ALTER TABLE tenants ADD COLUMN demo_hint TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_tenants_showcase ON tenants (is_showcase, product_id);
