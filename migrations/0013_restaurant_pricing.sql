-- سعر المطاعم: عشرون للأساسية وأربعون للكاملة.
--
-- كان الكتالوج يقول أربعين وستّين، وصاحب المنصّة يقول عشرين وأربعين حين
-- يُسأل. رقمان لشيءٍ واحد في مكانين — والذي يظهر في الفاتورة هو الذي في
-- القاعدة لا الذي في الرأس.
--
-- والقيم بالسنت: 2000 = 20.00$ و4000 = 40.00$. الأعمدة `_minor` كلّها
-- كذلك، فحفظ «20» فيها يعني عشرين سنتًا.
--
-- ولماذا ترحيلٌ وفي اللوحة شاشةٌ تعدّل السعر؟ لأن التعديل من الشاشة يمسّ
-- الإنتاج وحده: قاعدةٌ تُبنى من الهجرات (فحصٌ، أو استعادة بعد كارثة)
-- تعود بالأسعار القديمة. وقد وقع هذا فعلًا — بذرة الهجرة 0002 تقول
-- 1000/3000، والإنتاج يقول 4000/6000، وبينهما تعديلاتٌ يدوية لا أثر لها
-- في المستودع.

UPDATE plans SET default_price_minor = 2000, updated_at = datetime('now')
WHERE id = 'restaurant:menu';

UPDATE plans SET default_price_minor = 4000, updated_at = datetime('now')
WHERE id = 'restaurant:full';

-- الاشتراكات التجريبية وحدها تُصحَّح.
--
-- سعر الاشتراك يُنسَخ من الباقة لحظةَ الإنشاء ولا يُقرأ منها بعدها —
-- وهذا صحيح: من اتّفقتَ معه على سعرٍ لا يتغيّر سعره لأنك عدّلت قائمتك.
-- لكن `trialing` لم يتّفق أحدٌ فيه على شيء، وشاشة التجديدات تعرض رقمه،
-- فيقرأ صاحب المنصّة «ستّون دولارًا» عن تجربةٍ ثمنها أربعون.
--
-- والملغاة تُترك: تاريخٌ لا يُعاد كتابته.
UPDATE subscriptions
SET price_minor = (SELECT default_price_minor FROM plans WHERE plans.id = subscriptions.plan_id),
    updated_at = datetime('now')
WHERE status = 'trialing'
  AND plan_id IN ('restaurant:menu', 'restaurant:full');
